import io
NL = chr(10)
head = io.open('head.html', encoding='utf-8').read()
body = io.open('body.html', encoding='utf-8').read()
tail = io.open('tail.html', encoding='utf-8').read()
fonts = io.open('fonts.css', encoding='utf-8').read()
app_css  = io.open('app.css', encoding='utf-8').read()
land_css = io.open('landing.css', encoding='utf-8').read()
i18n_js  = io.open('i18n.js', encoding='utf-8').read()
core_js  = io.open('app-core.js', encoding='utf-8').read()
land_js  = io.open('landing.js', encoding='utf-8').read()
html = (head + '<style>' + NL + fonts + NL + app_css + NL + land_css + NL + '</style>'
        + body + '<script>' + NL + i18n_js + NL + core_js + NL + land_js + NL + '</script>' + tail)
io.open('../index.html', 'w', encoding='utf-8', newline=NL).write(html)
print('wrote ../index.html')
print('assembled:', len(html.encode('utf-8')), 'bytes')
